const BASE = Date.UTC(2026, 9, 31, 9, 0, 0);
/** A relay whose clock starts at 09:00 and moves a second per look; `advance` moves it further. */
function relay(o = {}) {
  let offset = 0;
  const now = () => { const t = new Date(BASE + offset).toISOString().replace(/\.\d{3}Z$/, "Z"); offset += 1000; return t; };
  const r = new Relay({ root: mkdtempSync(join(tmpdir(), "gemworks-relay-")), name: "relay.test", now, ...o });
  r.advance = (ms) => { offset += ms; };
  return r;
}
const ok = (x) => { assert.equal(x.ok, true, x.reason); return x; };
const bad = (x, status) => { assert.equal(x.ok, false); assert.equal(x.status, status, x.reason); return x; };

/** John with his agent 小评 (xiaoping), 张三 with 小测 (xiaoce, which takes no agent's `@`), a group g-7 of both people and both agents. */
function world(r = relay()) {
  const john = ok(r.issuePerson("john"));
  const zhang = ok(r.issuePerson("zhangsan"));
  const xiaoping = ok(r.issueAgent(john.record, "xiaoping"));
  const xiaoce = ok(r.issueAgent(zhang.record, "xiaoce", { promptFrom: "nobody", allow: [] }));
  ok(r.createVenue(john.record, { id: "g-7", kind: "group", name: "前端周会", people: ["zhangsan"], agents: ["agent:xiaoping@john", "agent:xiaoce@zhangsan"] }));
  return { r, john: john.record, zhang: zhang.record, xiaoping: xiaoping.record, xiaoce: xiaoce.record, tokens: { john: john.token, xiaoping: xiaoping.token } };
}
const say = (r, by, id, body) => ok(r.appendMessage(by, "john", "g-7", { id, ...body }));


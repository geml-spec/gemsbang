test("delivery: a person's leading @ fills the agent's queue with the venue's context; an agent's @ obeys the target's policy and the hop limit; a guest's DM word needs no @", () => {
  const { r, john, zhang, xiaoping } = world();
  const m1 = say(r, zhang, "m-1", { text: "@xiaoping 跑一下测试", expires: "2026-10-31T10:00:00Z" });
  assert.deepEqual(m1.delivery.prompts, [{ agent: "xiaoping", level: "member", hops: 0 }]);
  const q = ok(r.queueOf(xiaoping, "john", "xiaoping"));
  assert.equal(q.pending.length, 1);
  const item = q.pending[0];
  assert.deepEqual([item.id, item.prompt, item.sender, item.senderName, item.level, item.venue, item.venueKind, item.venueName, item.message, item.expires, item.hops, item.context], ["qi-g-7-m-1", "@xiaoping 跑一下测试", "person:zhangsan", "zhangsan", "member", "g-7", "group", "前端周会", "https://relay.test/john/venues/g-7.geml#m-1", "2026-10-31T10:00:00Z", 0, []]);
  ok(r.setAnnounce(john, "john", "g-7", "先跑测试再合"));
  ok(r.markDecision(zhang, "john", "g-7", "m-1"));
  const m2 = say(r, john, "m-2", { text: "@xiaoping @xiaoce 再来一次 @zhangsan 看看", parts: [{ src: "https://relay.test/john/journals/t-42.geml#rev-3" }] });
  assert.deepEqual(m2.delivery.prompts, [{ agent: "xiaoping", level: "owner", hops: 0 }, { agent: "xiaoce", level: "member", hops: 0 }], "a person's @ is always a prompt, policy or not");
  assert.deepEqual(m2.delivery.notified, ["zhangsan"]);
  const queued = ok(r.queueOf(xiaoping, "john", "xiaoping")).pending;
  assert.deepEqual(queued.map((i) => i.id), ["qi-g-7-m-2", "qi-g-7-m-1"], "the owner's prompt goes first");
  const second = queued[0];
  assert.deepEqual(second.context, [{ src: "https://relay.test/john/venues/g-7.geml#announce" }, { src: "https://relay.test/john/venues/g-7.geml#m-1" }, { src: "https://relay.test/john/journals/t-42.geml#rev-3" }], "the announce and the decisions as live embeds, then the message's own parts");
  assert.equal(ok(r.queueOf(zhang, "zhangsan", "xiaoce")).pending.length, 1);
  const m3 = say(r, xiaoping, "m-3", { text: "@xiaoce 你也跑一下", session: "cc-1", handling: 0 });
  assert.deepEqual(m3.delivery.prompts, []);
  assert.deepEqual(m3.delivery.degraded, [{ agent: "xiaoce", reason: "对方策略不收 agent 的指令，只当消息读到" }]);
  ok(r.addMember(john, "john", "g-7", "agent:xiaoguan@john"));
  const m4 = say(r, xiaoping, "m-4", { text: "@xiaoguan 接着干", session: "cc-1", handling: 3 });
  assert.deepEqual(m4.delivery.degraded, [{ agent: "xiaoguan", reason: "超过 3 跳" }]);
  const sys = r.venueOf("john", "g-7").messages.filter((m) => m.kind === "system").map((m) => m.text);
  assert.ok(sys.includes("给 xiaoguan 的指令是第 4 跳，超过上限 3 跳，按普通消息投递，没有进它的队列"), sys.join("\n"));
  const m5 = say(r, xiaoping, "m-5", { text: "@xiaoguan 接着干", session: "cc-1", handling: 1 });
  assert.deepEqual(m5.delivery.prompts, [{ agent: "xiaoguan", level: "owner", hops: 2 }]);
  assert.equal(readDoc(r.root, "john", "queues/xiaoguan.geml").blocks[0].value.hops, 2);
  const guest = ok(r.issueGuest()).record;
  ok(r.createVenue(john, { id: "gd-1", kind: "guest-dm", name: "访客", people: [guest.speaker], agents: ["agent:xiaoping@john"] }));
  assert.equal(r.venueOf("john", "gd-1").venue.host, "xiaoping");
  const g1 = ok(r.appendMessage(guest, "john", "gd-1", { id: "g-1", text: "这个项目怎么跑？" }));
  assert.deepEqual(g1.delivery.prompts, [{ agent: "xiaoping", level: "guest", hops: 0 }]);
  const gi = ok(r.queueOf(john, "john", "xiaoping")).pending.find((i) => i.venue === "gd-1");
  assert.deepEqual([gi.senderName, gi.level, gi.venueKind], [`访客 ${guest.speaker.slice("guest:".length)}`, "guest", "guest-dm"]);
  ok(r.trust(john, "zhangsan"));
  assert.deepEqual(say(r, zhang, "m-6", { text: "@xiaoping 再跑" }).delivery.prompts, [{ agent: "xiaoping", level: "trusted", hops: 0 }]);
});

